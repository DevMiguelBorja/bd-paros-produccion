COMMENT ON TABLE area_impacto        IS 'Áreas de la empresa a las que se atribuye un paro';
COMMENT ON TABLE codigo_paro         IS 'Los 18 códigos de paro del procedimiento P-MTO-22';
COMMENT ON TABLE subcodigo_paro      IS 'Subcódigos jerárquicos de los códigos 01, 03 y 05';
COMMENT ON TABLE maquina             IS 'Líneas de envasado Vinilos_1 a Vinilos_4';
COMMENT ON TABLE turno               IS 'Franjas de trabajo normalizadas';
COMMENT ON TABLE empleado            IS 'Operarios y personal de mantenimiento (datos personales)';
COMMENT ON TABLE referencia          IS 'Productos envasados: marca, volumen y colores';
COMMENT ON TABLE tipo_paro_jornada   IS 'Motivo cuando la jornada no se trabajó total o parcialmente';
COMMENT ON TABLE registro_produccion IS 'Un registro por máquina, fecha, turno y referencia (formato hora a hora)';
COMMENT ON TABLE paro                IS 'Cada paro dentro de un registro: código, subcódigo y minutos';