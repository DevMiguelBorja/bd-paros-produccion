
DROP SCHEMA IF EXISTS paros CASCADE;
CREATE SCHEMA paros;
SET search_path TO paros;

-- ---------------------------------------------------------------------
-- 1. CATÁLOGOS
-- ---------------------------------------------------------------------
CREATE TABLE area_impacto (
    id_area   SMALLINT    GENERATED BY DEFAULT AS IDENTITY,
    nombre    VARCHAR(40) NOT NULL,
    CONSTRAINT pk_area_impacto        PRIMARY KEY (id_area),
    CONSTRAINT uq_area_impacto_nombre UNIQUE (nombre)
);

CREATE TABLE codigo_paro (
    id_codigo SMALLINT     NOT NULL,                 -- código de negocio 1..18
    nombre    VARCHAR(100) NOT NULL,
    id_area   SMALLINT     NOT NULL,
    CONSTRAINT pk_codigo_paro        PRIMARY KEY (id_codigo),
    CONSTRAINT ck_codigo_paro_id     CHECK (id_codigo BETWEEN 1 AND 99),
    CONSTRAINT uq_codigo_paro_nombre UNIQUE (nombre),
    CONSTRAINT fk_codigo_area FOREIGN KEY (id_area)
        REFERENCES area_impacto (id_area)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE subcodigo_paro (
    id_subcodigo SMALLINT     GENERATED BY DEFAULT AS IDENTITY,
    id_codigo    SMALLINT     NOT NULL,
    clave        VARCHAR(10)  NOT NULL,              -- p. ej. '1.2.B'
    nombre       VARCHAR(100) NOT NULL,
    id_padre     SMALLINT,                           -- NULL = sistema de primer nivel
    CONSTRAINT pk_subcodigo_paro      PRIMARY KEY (id_subcodigo),
    CONSTRAINT uq_subcodigo_clave     UNIQUE (id_codigo, clave),
    CONSTRAINT uq_subcodigo_codigo_id UNIQUE (id_codigo, id_subcodigo),  -- requerido por la FK compuesta de paro
    CONSTRAINT ck_subcodigo_codigos   CHECK (id_codigo IN (1, 3, 5)),    -- solo 01, 03 y 05 tienen subcódigos
    CONSTRAINT ck_subcodigo_padre     CHECK (id_padre IS NULL OR id_padre <> id_subcodigo),
    CONSTRAINT fk_subcodigo_codigo FOREIGN KEY (id_codigo)
        REFERENCES codigo_paro (id_codigo)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_subcodigo_padre FOREIGN KEY (id_padre)
        REFERENCES subcodigo_paro (id_subcodigo)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE maquina (
    id_maquina SMALLINT    GENERATED BY DEFAULT AS IDENTITY,
    nombre     VARCHAR(30) NOT NULL,
    CONSTRAINT pk_maquina        PRIMARY KEY (id_maquina),
    CONSTRAINT uq_maquina_nombre UNIQUE (nombre)
);

CREATE TABLE turno (
    id_turno    SMALLINT    GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(30) NOT NULL,
    hora_inicio TIME        NOT NULL,
    hora_fin    TIME        NOT NULL,                -- puede ser menor que hora_inicio (turno nocturno)
    CONSTRAINT pk_turno        PRIMARY KEY (id_turno),
    CONSTRAINT uq_turno_nombre UNIQUE (nombre)
);

CREATE TABLE empleado (
    id_empleado INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    nombre      VARCHAR(80) NOT NULL,                -- dato personal: ver docs/09_datos-personales.md
    tipo        VARCHAR(15) NOT NULL,
    CONSTRAINT pk_empleado        PRIMARY KEY (id_empleado),
    CONSTRAINT uq_empleado_nombre UNIQUE (nombre, tipo),
    CONSTRAINT ck_empleado_tipo   CHECK (tipo IN ('OPERARIO', 'MANTENIMIENTO'))
);

CREATE TABLE referencia (
    id_referencia   INTEGER     GENERATED BY DEFAULT AS IDENTITY,
    nombre_original VARCHAR(60) NOT NULL,            -- texto tal como se digita en el formato
    marca           VARCHAR(40),
    volumen_cc      SMALLINT,
    num_colores     SMALLINT,
    CONSTRAINT pk_referencia        PRIMARY KEY (id_referencia),
    CONSTRAINT uq_referencia_nombre UNIQUE (nombre_original),
    CONSTRAINT ck_referencia_volumen CHECK (volumen_cc  IS NULL OR volumen_cc  > 0),
    CONSTRAINT ck_referencia_colores CHECK (num_colores IS NULL OR num_colores > 0)
);

CREATE TABLE tipo_paro_jornada (
    id_tipo_paro SMALLINT     GENERATED BY DEFAULT AS IDENTITY,
    nombre       VARCHAR(100) NOT NULL,
    CONSTRAINT pk_tipo_paro_jornada     PRIMARY KEY (id_tipo_paro),
    CONSTRAINT uq_tipo_paro_jornada_nom UNIQUE (nombre)
);

-- ---------------------------------------------------------------------
-- 2. TABLAS TRANSACCIONALES
-- ---------------------------------------------------------------------
CREATE TABLE registro_produccion (
    id_registro         INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    fecha               DATE          NOT NULL,
    id_maquina          SMALLINT      NOT NULL,
    id_turno            SMALLINT,                    
    id_operario         INTEGER,
    id_referencia       INTEGER,
    horas_trabajadas    NUMERIC(5,2)  NOT NULL DEFAULT 0,
    horas_no_trabajadas NUMERIC(5,2)  NOT NULL DEFAULT 0,
    pacas_producidas    INTEGER       NOT NULL DEFAULT 0,
    id_tipo_paro        SMALLINT,
    observacion_paro    VARCHAR(100),
    observaciones       VARCHAR(500),
    CONSTRAINT pk_registro_produccion PRIMARY KEY (id_registro),
    CONSTRAINT ck_registro_fecha      CHECK (fecha >= DATE '2020-01-01'),
    CONSTRAINT ck_registro_horas_trab CHECK (horas_trabajadas BETWEEN 0 AND 24),
    CONSTRAINT ck_registro_horas_no   CHECK (horas_no_trabajadas >= 0),
    CONSTRAINT ck_registro_pacas      CHECK (pacas_producidas >= 0),
    CONSTRAINT fk_registro_maquina FOREIGN KEY (id_maquina)
        REFERENCES maquina (id_maquina)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_registro_turno FOREIGN KEY (id_turno)
        REFERENCES turno (id_turno)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_registro_operario FOREIGN KEY (id_operario)
        REFERENCES empleado (id_empleado)
        ON UPDATE CASCADE ON DELETE SET NULL,       
    CONSTRAINT fk_registro_referencia FOREIGN KEY (id_referencia)
        REFERENCES referencia (id_referencia)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_registro_tipo_paro FOREIGN KEY (id_tipo_paro)
        REFERENCES tipo_paro_jornada (id_tipo_paro)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE paro (
    id_paro       INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    id_registro   INTEGER      NOT NULL,
    id_codigo     SMALLINT     NOT NULL,
    id_subcodigo  SMALLINT,
    minutos       NUMERIC(6,1) NOT NULL,
    id_empleado   INTEGER,                           
    area_atencion VARCHAR(15),                       
    CONSTRAINT pk_paro PRIMARY KEY (id_paro),
    CONSTRAINT ck_paro_minutos CHECK (minutos > 0),
    CONSTRAINT ck_paro_area    CHECK (area_atencion IS NULL OR area_atencion IN ('OPERARIOS', 'MANTENIMIENTO')),
    CONSTRAINT ck_paro_solo_codigo5
        CHECK (id_codigo = 5 OR (id_empleado IS NULL AND area_atencion IS NULL)),
    CONSTRAINT fk_paro_registro FOREIGN KEY (id_registro)
        REFERENCES registro_produccion (id_registro)
        ON UPDATE CASCADE ON DELETE CASCADE,       
    CONSTRAINT fk_paro_codigo FOREIGN KEY (id_codigo)
        REFERENCES codigo_paro (id_codigo)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_paro_subcodigo FOREIGN KEY (id_codigo, id_subcodigo)   
        REFERENCES subcodigo_paro (id_codigo, id_subcodigo)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_paro_empleado FOREIGN KEY (id_empleado)
        REFERENCES empleado (id_empleado)
        ON UPDATE CASCADE ON DELETE SET NULL
);

-- ---------------------------------------------------------------------
